/// Provides server metadata and capabilities for MCP clients.
#[tool_handler]
impl ServerHandler for RouterTools {
    fn get_info(&self) -> ServerInfo {
        ServerInfo::new(
            rmcp::model::ServerCapabilities::builder()
                .enable_tools()
                .build(),
        )
        .with_server_info(
            Implementation::new(app::app_name(), app::app_version())
                .with_title("Vibe Analyzer")
                .with_description("Code & knowledge base."),
        )
        .with_protocol_version(self.state.protocol_version.clone())
        .with_instructions(
            r#"
RULES:
1. Use tools, answer concisely.
2. ONE tool call is enough.
3. ONLY listed tools.
"#,
        )
    }
}

/// Aggregates all MCP tools and provides routing logic.
#[derive(Clone)]
